// ---------------------------------------------------------------------
// Summary
// ---------------------------------------------------------------------
// - `renderToStaticMarkup` renders a React tree into a non-interactive HTML string.
// - It is imported from `react-dom/server`.
// - The API is intended for static HTML generation such as documents, emails, and simple static pages.
// - The returned value is an HTML string, not a browser DOM node.
// - Event handlers are not attached to the generated HTML.
// - Output from `renderToStaticMarkup` cannot be hydrated with `hydrateRoot`.
// - Use a hydratable server-rendering API when the generated HTML must become an interactive React application.
// - `renderToStaticMarkup` has limited Suspense support and renders a Suspense fallback when content suspends.
// - `renderToStaticMarkup` does not progressively stream Suspense content as it becomes available.
// - `identifierPrefix` can be used to prefix IDs generated by React's `useId`.
// - Static output can still contain normal HTML elements, attributes, forms, links, and other browser-native behavior.
// - "Static" describes the generated HTML output; the data used to produce that output can still be dynamic.
// - `renderToStaticMarkup` is a specialized server API for producing HTML that does not need React hydration.
