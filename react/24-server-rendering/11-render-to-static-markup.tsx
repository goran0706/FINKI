/**
 * Render To Static Markup
 * =======================
 *
 * `renderToStaticMarkup` renders a React tree into a non-interactive HTML string on the server.
 * The output is intended for static HTML use cases such as emails, documents, and simple static
 * pages where the generated markup does not need to be hydrated into an interactive React tree.
 */

import { renderToStaticMarkup } from "react-dom/server";
import { Suspense, use, type FC, type ReactElement } from "react";

// ---------------------------------------------------------------------
// 1. Basic static rendering
// ---------------------------------------------------------------------

export const Greeting: FC = (): ReactElement => {
  return (
    <section>
      <h1>Hello, John Doe</h1>
      <p>Welcome to the example application.</p>
    </section>
  );
};

export const renderGreeting = (): string => {
  return renderToStaticMarkup(<Greeting />);
};

const greetingMarkup = renderGreeting();

console.log(greetingMarkup);

// `renderToStaticMarkup` returns an HTML string.
// The result contains the rendered markup but does not represent a live React tree.

// ---------------------------------------------------------------------
// 2. Rendering component props
// ---------------------------------------------------------------------

interface UserCardProps {
  readonly name: string;
  readonly email: string;
}

export const UserCard: FC<UserCardProps> = ({ name, email }): ReactElement => {
  return (
    <article>
      <h2>{name}</h2>
      <p>{email}</p>
    </article>
  );
};

export const renderUserCard = (name: string, email: string): string => {
  return renderToStaticMarkup(<UserCard name={name} email={email} />);
};

const userCardMarkup = renderUserCard("John Doe", "john.doe@example.com");

console.log(userCardMarkup);

// Props are resolved while React renders the component tree.
// The returned value is ordinary HTML text.

