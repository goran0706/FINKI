// The resulting string can then be sent, stored, or embedded by the server.

// ---------------------------------------------------------------------
// 4. Static output is not hydrated
// ---------------------------------------------------------------------

export const InteractiveButton: FC = (): ReactElement => {
  return (
    <button
      type="button"
      onClick={() => {
        console.log("Clicked");
      }}
    >
      Continue
    </button>
  );
};

export const renderInteractiveButtonAsStaticMarkup = (): string => {
  return renderToStaticMarkup(<InteractiveButton />);
};

const staticButtonMarkup = renderInteractiveButtonAsStaticMarkup();

console.log(staticButtonMarkup);

// The `onClick` function does not become an active event listener in the HTML string.
// `renderToStaticMarkup` produces non-interactive HTML and its output cannot be hydrated.

// ---------------------------------------------------------------------
// 5. Static markup versus hydratable server markup
// ---------------------------------------------------------------------

export const Application: FC = (): ReactElement => {
  return (
    <main>
      <h1>Example Application</h1>
      <button type="button">Continue</button>
    </main>
  );
};

export const renderAsStaticMarkup = (): string => {
  return renderToStaticMarkup(<Application />);
};

// Static markup is intended for output that does not need React hydration.
// A hydratable application should instead use a server rendering API whose output
// is designed to work with `hydrateRoot`.

