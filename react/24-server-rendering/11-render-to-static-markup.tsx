// ---------------------------------------------------------------------
// 8. Lists and dynamic content
// ---------------------------------------------------------------------

interface Product {
  readonly id: number;
  readonly name: string;
  readonly price: string;
}

const products: Product[] = [
  {
    id: 1,
    name: "Example Product",
    price: "$19.99",
  },
  {
    id: 2,
    name: "Another Product",
    price: "$29.99",
  },
  {
    id: 3,
    name: "Third Product",
    price: "$39.99",
  },
];

export const ProductList: FC = (): ReactElement => {
  return (
    <ul>
      {products.map((product) => (
        <li key={product.id}>
          <strong>{product.name}</strong>
          {" — "}
          <span>{product.price}</span>
        </li>
      ))}
    </ul>
  );
};

export const renderProductList = (): string => {
  return renderToStaticMarkup(<ProductList />);
};

// Dynamic JavaScript data can still determine the static output.
// "Static" describes the resulting HTML, not necessarily how the data was prepared.

