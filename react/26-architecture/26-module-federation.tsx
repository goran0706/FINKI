// ---------------------------------------------------------------------
// Summary
// ---------------------------------------------------------------------
// - Module Federation allows independently built applications to expose and consume modules at runtime.
// - A host consumes exposed modules, while a remote exposes modules for other applications to load.
// - Runtime loading does not automatically create a good architectural boundary.
// - Exposed modules should represent meaningful capabilities rather than arbitrary internal components.
// - Internal state, repositories, hooks, and implementation details should remain private.
// - A small exposed surface reduces compatibility and coordination costs.
// - Independent deployment requires stable public contracts and deliberate compatibility management.
// - Module Federation can share dependencies such as React, but sharing creates version and runtime coordination requirements.
// - Shared dependencies should be selected deliberately rather than shared indiscriminately.
// - Sharing React can simplify React-specific composition, context, hooks, and element interoperability when compatible runtimes are used.
// - Isolating runtimes can provide greater independence at the cost of duplication and reduced runtime integration.
// - Module Federation is a module-loading mechanism, not a replacement for APIs, state management, authentication, or domain boundaries.
// - Data ownership should remain with the capability that owns the corresponding business responsibility.
// - Events, commands, callbacks, URLs, and APIs provide different mechanisms for communication across federated boundaries.
// - Direct access to another remote's internal state, DOM, repository, or implementation creates hidden coupling.
// - Public DTOs and boundary adapters can prevent internal data models from leaking across application boundaries.
// - Loading, timeout, retry, and failure behavior are part of the runtime integration contract.
// - Remote observability should include loading, rendering, and runtime failure information with capability identity.
// - Module Federation can work with monorepos or polyrepos; repository organization and runtime deployment are separate decisions.
// - A monorepo does not prevent independent deployment, and independent deployment does not require separate repositories.
// - Contract validation and compatibility testing become increasingly important when hosts and remotes deploy independently.
// - Version compatibility is more important than identical version numbers.
// - Temporary compatibility windows and deprecation periods can allow hosts and remotes to evolve independently.
// - Security matters because federated remote code executes in the host's runtime context and is not automatically sandboxed.
// - Iframes provide stronger runtime isolation, while Module Federation provides tighter in-page JavaScript integration.
// - Module Federation can support different frontend technologies, but framework-neutral integration introduces additional interoperability work.
// - A federated architecture becomes a distributed monolith when remotes still require shared internal state, internal imports, or synchronized releases.
// - Module Federation should support deliberate capability boundaries rather than being used as a substitute for architectural boundaries.
