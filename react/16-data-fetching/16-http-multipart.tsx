// ---------------------------------------------------------------------
// Summary
// ---------------------------------------------------------------------
// - Multipart HTTP bodies contain multiple independently encoded parts.
// - multipart/form-data is commonly used for HTML forms that include files.
// - Each multipart body uses a boundary to separate its parts.
// - Multipart parts can contain their own headers and content.
// - Content-Disposition commonly identifies a form field with a name parameter.
// - File parts can also include a filename parameter in Content-Disposition.
// - FormData can combine ordinary string fields with File or Blob values.
// - Fetch generates the multipart boundary when FormData is used as a request body.
// - Application code should not manually set Content-Type for a browser-managed FormData request.
// - URL-encoded form data is primarily suited to textual key-value pairs.
// - Multipart form data can transport both textual fields and binary file content.
// - A multipart boundary must correspond to the delimiters used in the encoded body.
