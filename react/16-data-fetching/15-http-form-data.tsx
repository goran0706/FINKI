// ---------------------------------------------------------------------
// Summary
// ---------------------------------------------------------------------
// - FormData represents key-value pairs for form submissions.
// - FormData supports string, Blob, and File values.
// - append() adds another value without removing existing values.
// - set() replaces all existing values for a field name.
// - get() returns the first value associated with a field name.
// - getAll() returns every value associated with a field name.
// - File is a Blob subtype that also carries file metadata.
// - A Blob can be supplied with an explicit filename when appended to FormData.
// - Passing FormData as a Fetch request body produces multipart/form-data encoding.
// - The multipart boundary should be generated by the browser rather than manually assigned.
// - FormData is suitable for forms that combine ordinary fields with uploaded files.
// - FormData and URLSearchParams represent different encoding strategies.
// - FormData values can be inspected with get(), getAll(), has(), delete(), and iteration methods.
