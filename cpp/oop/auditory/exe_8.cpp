/*
    2.1. Триаголник

    Да се напише класа за опишување на геометриско тело триаголник.
    Во класата да се напишат методи за пресметување на плоштината и периметарот на триаголникот.

    Потоа да се напише главна програма во која ќе се инстнацира еден објект од оваа класа со вредности за страните
    кои претходно ќе се прочитаат од стандарден влез.

    На овој објект да се повикат соодветните методи за пресметување на плоштината и периметарот.
*/

#include <iostream>
#include <ostream>
#include <cmath> // Потребно за sqrt() пресметката на плоштина
using namespace std;

// ============================================================================
// АПСТРАКТНА КЛАСА (Abstract Class)
// ============================================================================

// class -> Клучен збор за дефинирање класа каде членовите се приватни по стандард.
class Shape {
    // private -> Секција во која сè што е дефинирано не е достапно надвор од класата.
private:
    // public -> Секција во која сè што е дефинирано е достапно надвор од класата.
public:
    // Shape() -> Стандарден конструктор (Default Constructor).
    // Shape() = default;
    // = default -> Му кажува на компајлерот сам да ја генерира наједноставната имплементација.
    Shape() {
        cout << "[Shape] Конструктор: Се креира генеричка форма." << endl;
    }

    /* ========================================================================
       ОБЈАСНУВАЊЕ: ЗОШТО КОНСТРУКТОР НЕМА 'virtual', А ДЕСТРУКТОР ИМА?
       ========================================================================
       1. КОНСТРУКТОР НЕ МОЖЕ ДА БИДЕ 'virtual':
          - За да работи 'virtual' (динамички полиморфизам), C++ користи скриена
            табела во меморијата наречена vtable (Virtual Table).
          - Оваа vtable табела се креира и се поврзува со објектот ДУРИ ОТКАКО
            конструкторот целосно ќе заврши со работа.
          - Додека се извршува конструкторот, објектот сè уште „не е комплетен“
            и не постои механизам кој би го пренасочил повикот виртуелно.
          - Исто така, ти секогаш точно знаеш кој објект го креираш во моментот
            (на пр. `new Triangle()`), pa нема потреба од динамичко одлучување.

       2. ДЕСТРУКТОР МОРА ДА БИДЕ 'virtual' КАЈ ХИЕРАРХИИ:
          - Ако имаме покажувач од типот на родителот кој покажува кон детето:
            `Shape* s = new Triangle(3, 4, 5);`
          - Кога ќе повикаме `delete s;`, ако деструкторот НЕ е виртуелен,
            C++ ќе го погледне само типот на покажувачот (`Shape*`) и ќе го
            повика САМО деструкторот на `Shape`. Деструкторот на `Triangle`
            нема ни да се изврши, што предизвикува ИСПУШТАЊЕ МЕМОРИЈА (Memory Leak).
          - Кога деструкторот е `virtual`, преку vtable табелата C++ знае дека
            зад тој покажувач всушност се крие `Triangle`, па правилно го повикува
            прво деструкторот на детето, па потоа на родителот.
    */

    // ~Shape() -> Стандарден деструктор (Default Destructor).
    // ~Shape() = default;
    // = default -> Му кажува на компајлерот сам да ја генерира наједноставната имплементација.
    // virtual -> Овозможува динамичко поврзување (полиморфизмот).
    // Кога се брише Shape*, се извршува деструкторот на точната изведена класа (на пр. Triangle).
    virtual ~Shape() {
        cout << "[Shape] Деструктор: Се уништува генеричката форма." << endl;
    }

    /*
       ========================================================================
       ДОДАТОК: МОЖНИ ВИДОВИ НА МЕТОДИ ВО АПСТРАКТНА КЛАСА
       ========================================================================
    */

    // --- 1. ЧИСТА ВИРТУЕЛНА ФУНКЦИЈА (Pure Virtual Function) ---
    // Мора да се дефинира во Triangle
    // [[nodiscard]] -> Атрибут кој јавува предупредување (warning) ако некој ја повика функцијата, а го игнорира резултатот.
    // virtual ... = 0 -> Чиста виртуелна функција (Pure Virtual Function). Ова ја претвора класата во АПСТРАКТНА.
    // const -> Гарантира дека овој метод нема да промени ниту една променлива во класата.
    [[nodiscard]] virtual double area() const = 0;

    [[nodiscard]] virtual int perimeter() const = 0;

    // --- 2. ОБИЧНА ВИРТУЕЛНА ФУНКЦИЈА (Virtual Function со тело) ---
    // Triangle може, но не мора да ја препише
    // Овој метод ИМА почетна имплементација, што значи дека изведените класи (како Triangle)
    // НЕ МОРААТ рачно да го пишуваат ако им одговара оваа логика.
    // Но, бидејќи има клуч збор `virtual`, тие ИМААТ ПРАВО да го препишат (override) ако сакаат сопствена логика.
    virtual void print_type() const {
        cout << "Јас сум генеричка геометриска форма." << endl;
    }

    // --- 3. НОРМАЛНА / НЕ-ВИРТУЕЛЕН ФУНКЦИЈА (Standard Member Function) ---
    // Ова е обична функција која има комплетно тело.
    // Таа е СТАТИЧНА во смисла на логика — изведените класи едноставно ја наследуваат и ја користат „готова“ каква што е.
    // Не е наменета за препишување (нема `virtual`), бидејќи логиката е идентична за сите форми.
    void print_welcome_message() const {
        cout << "Добредојдовте во математичкиот систем за форми!" << endl;
    }
};

// ============================================================================
// ИЗВЕДЕНА КЛАСА (Derived Class) - ТРИАГОЛНИК
// ============================================================================
// ПРЕГЛЕД НА СИТЕ МОЖНОСТИ ЗА НАСЛЕДУВАЊЕ ВО C++:
//
// 1. : public Shape (Јавно наследување) -> УПОТРЕБЕНО ТУКА
//    - Ги задржува правата: public станува public, protected станува protected.
//    - Овозможува полиморфизам (`Shape* s = new Triangle()`). Однос: „Е-еден“ (Is-A).
//
// 2. : protected Shape (Заштитено наследување)
//    - Ги стеснува правата: public и protected од родителот стануваат protected во детето.
//    - Надворешниот свет во `main` губи пристап до нив, но идните поткласи (внуци) сè уште ги гледаат.
//
// 3. : private Shape (Приватно наследување)
//    - Ги заклучува правата: public и protected стануваат private во изведената класа.
//    - Идните генерации и надворешниот свет немаат никаков пристап. Однос: „Имплементирано преку“.
//
// 4. : virtual public Shape (Виртуелно наследување)
//    - Се користи кај повеќекратно наследување за да се реши „Дијамантскиот проблем“.
//    - Гарантира дека ќе се креира само ЕДНА споделена копија од `Shape` во меморијата.
// ============================================================================
class Triangle : public Shape {
    // class -> Клучен збор за дефинирање класа каде членовите се приватни по стандард.

private:
    // private -> Секција достапна САМО за членовите на оваа класа (Капсулација).

    int a = 0; // Променлива (член-податок) за страната а
    int b = 0; // Променлива (член-податок) за страната b
    int c = 0; // Променлива (член-податок) за страната c

public:
    // public -> Секција во која сè што е дефинирано е достапно надвор од класата.

    /* ========================================================================
       РЕДОСЛЕД НА ИЗВРШУВАЊЕ ПРИ ОБИЧНО НАСЛЕДУВАЊЕ:
       ========================================================================
       - Конструктори: Прво се повикува Shape() (родител), па дури потоа Triangle() (дете).
       - Деструктори: Прво се повикува ~Triangle() (дете), па на крајот ~Shape() (родител).
    */

    // ========================================================================
    // DEFAULT CONSTRUCTOR (Стандарден конструктор)
    // ========================================================================
    // ТЕХНИЧКО ОБЈАСНУВАЊЕ:
    // Triangle()       -> Експлицитен конструктор без параметри кој спречува „garbage“ вредности во меморијата.
    // : Shape()        -> Експлицитен повик на конструкторот на родителот.
    // : a(1), b(1)...  -> Листа за иницијализација. Поефикасна од доделување вредности во самото тело `{}`.
    //
    // КОГА СЕ ПОВИКУВА (USAGE):
    // Се повикува при креирање објект без да се пратат почетни вредности за страните.
    // Пример во main:
    //    Triangle t; // <--- Поставени дефолт страни (1,1,1)
    Triangle() : Shape(), a(1), b(1), c(1) {
        cout << "[Triangle] Стандарден конструктор: Поставени дефолт страни (1,1,1)." << endl;
    }

    // ========================================================================
    // PARAMETERIZED CONSTRUCTOR (Параметарски конструктор)
    // ========================================================================
    // ТЕХНИЧКО ОБЈАСНУВАЊЕ:
    // const int a      -> Аргументите се константни во рамките на овој конструктор и не можат да се менуваат.
    // a(a), b(b)...    -> Членовите на класата директно ги примаат вредностите од аргументите преку листа за иницијализација.
    //
    // КОГА СЕ ПОВИКУВА (USAGE):
    // Се повикува кога креираме нов објект и сакаме веднаш да му доделиме конкретни вредности.
    // Пример во main:
    //    Triangle t1(3, 4, 5); // <--- Креира триаголник со точно зададени страни
    Triangle(const int a, const int b, const int c)
        : Shape(),
          a(a),
          b(b),
          c(c) {
        cout << "[Triangle] Параметарски конструктор: "
                "Се креира триаголник со страни (" << a << ", " << b << ", " << c << ")." << endl;
    }

    // ========================================================================
    // COPY CONSTRUCTOR (Конструктор за копирање)
    // ========================================================================
    // ТЕХНИЧКО ОБЈАСНУВАЊЕ:
    // const Triangle &other -> Референца до постоечки објект (спречува бесконечно копирање).
    // const                 -> Ветување дека оригиналниот објект 'other' нема да се промени додека копираме.
    //
    // КОГА СЕ ПОВИКУВА (USAGE):
    // Се повикува кога се раѓа / иницијализира сосем нов објект како копија на постоечки.
    // Пример во main:
    //    Triangle t1(3, 4, 5);
    //    Triangle t2 = t1; // <--- ГО ПОВИКУВА ОВОЈ КОНСТРУКТОР (t2 е нов, t1 веќе постоел)
    Triangle(const Triangle &other)
        : Shape(),
          a(other.a),
          b(other.b),
          c(other.c) {
        cout << "[Copy Constructor]" << endl;
    }

    // ========================================================================
    // MOVE CONSTRUCTOR (Конструктор за поместување)
    // ========================================================================
    // ТЕХНИЧКО ОБЈАСНУВАЊЕ:
    // Triangle &&other -> Rvalue референца. Означува привремен објект пред уништување.
    // noexcept         -> Ветување дека методот гарантирано нема да фрли исклучок (клучно за брзината).
    //
    // КОГА СЕ ПОВИКУВА (USAGE):
    // Се повикува кога се креира нов објект од привремен анонимен објект или преку std::move.
    // Пример во main:
    //    Triangle t3 = Triangle(6, 8, 10); // <--- Привремениот се „поместува“ директно во t3
    Triangle(Triangle &&other) noexcept
        : Shape(),
          a(other.a),
          b(other.b),
          c(other.c) {
        cout << "[Move Constructor]" << endl;
    }

    // ========================================================================
    // 1. COPY ASSIGNMENT OPERATOR (Оператор за копирање со доделување)
    // ========================================================================
    // ТЕХНИЧКО ОБЈАСНУВАЊЕ:
    // Triangle & -> Враќа референца до самиот тековен објект (овозможува надоврзување како t1 = t2 = t3).
    // operator=  -> Преоптоварување на операторот за доделување вредност.
    // this       -> Покажувач (pointer) до тековниот објект во кој се наоѓаме.
    // &other     -> Адресата на другиот објект.
    // if (this == &other) -> Заштита од само-доделување (на пр. ако корисникот напише t1 = t1;).
    // *this      -> Го дереференцира покажувачот за да го врати самиот објект како вредност.
    //
    // КОГА СЕ ПОВИКУВА (USAGE):
    // Се повикува кога од десната страна на знакот '=' има ТРАЕН објект со име (lvalue).
    // Оригиналниот објект мора да остане целосно недопрен по операцијата.
    // Пример во main:
    //    Triangle t1(3, 4, 5);
    //    Triangle t2;
    //    t2 = t1;  // <--- ГО ПОВИКУВА ОВОЈ ОПЕРАТОР (t1 и понатаму си постои нормално)
    Triangle &operator=(const Triangle &other) {
        cout << "[Copy Assignment Operator]" << endl;
        if (this == &other) return *this;
        a = other.a;
        b = other.b;
        c = other.c;
        return *this;
    }

    // ========================================================================
    // 2. MOVE ASSIGNMENT OPERATOR (Оператор за поместување со доделување)
    // ========================================================================
    // ТЕХНИЧКО ОБЈАСНУВАЊЕ:
    // Triangle&& -> Rvalue референца. Прифаќа привремени објекти кои веднаш „умираат“.
    // noexcept   -> Ветување кон компајлерот дека нема да фрли исклучок (важно за оптимизација).
    //
    // КОГА СЕ ПОВИКУВА (USAGE):
    // Се повикува во две ситуации:
    // 1. Кога од десната страна има ПРИВРЕМЕН/АНОНИМЕН објект без име (rvalue).
    // 2. Кога експлицитно го присилуваме компајлерот преку функцијата `std::move()`.
    // Бидејќи десниот објект веднаш ќе се уништи, овој оператор му ги „краде“ ресурсите наместо безбедно да ги копира.
    // Пример во main:
    //    Triangle t3;
    //    t3 = Triangle(10, 10, 10); // <--- Ситуација 1: Доделување привремен објект
    //
    //    Triangle t4(5, 5, 5);
    //    t3 = std::move(t4);        // <--- Ситуација 2: Експлицитно празнење на t4
    Triangle &operator=(Triangle &&other) noexcept {
        cout << "[Move Assignment Operator]" << endl;
        if (this == &other) return *this;
        a = other.a;
        b = other.b;
        c = other.c;
        return *this;
    }

    // ========================================================================
    // DESTRUCTOR (Деструктор)
    // ========================================================================
    // ТЕХНИЧКО ОБЈАСНУВАЊЕ:
    // ~Triangle() -> Се повикува автоматски кога објектот излегува од опсег (scope) со цел чистење меморија.
    // override    -> Гарантира дека деструкторот точно го препишува виртуелниот деструктор (~Shape()) од родителот.
    //
    // КОГА СЕ ПОВИКУВА (USAGE):
    // Се активира автоматски кога програмата завршува или кога се брише покажувач преку `delete`.
    // Пример во main:
    //    При излез од `return 0;`, сите локални објекти автоматски се уништуваат во обратен редослед.
    ~Triangle() override {
        cout << "[Triangle] Деструктор: Се уништува триаголникот." << endl;
    }

    // --- ГЕТЕРИ И СЕТЕРИ (Getters & Setters) ---

    // get_a() -> Гетер метод за безбедно читање на приватната страна 'a'.
    [[nodiscard]] int get_a() const { return a; }

    // set_a(int a) -> Сетер метод за менување на приватната страна 'a'.
    // this->a = a; -> Разликување: 'this->a' е приватната променлива на класата, а обичното 'a' е аргументот од функцијата.
    void set_a(int a) { this->a = a; }

    [[nodiscard]] int get_b() const { return b; }
    void set_b(int b) { this->b = b; }

    [[nodiscard]] int get_c() const { return c; }
    void set_c(int c) { this->c = c; }

    // --- ПРИЈАТЕЛСКИ ОПЕРАТОРИ ЗА СПОРЕДБА (Friend Operators) ---
    // friend -> Иако овие функции се дефинирани ТЕХНИЧКИ НАДВОР ОД КЛАСАТА, клучниот збор friend
    // им дава специјална дозвола директно да пристапуваат до приватните податоци (a, b, c).

    // operator== -> Го преоптоварува операторот за еднаквост.
    // lhs -> Left-Hand Side (Објектот од левата страна на операторот '==')
    // rhs -> Right-Hand Side (Објектот од десната страна на операторот '==')
    friend bool operator==(const Triangle &lhs, const Triangle &rhs) {
        return lhs.a == rhs.a && lhs.b == rhs.b && lhs.c == rhs.c;
    }

    // operator!= -> Оператор за нееднаквост. Ја користи логичката негација (!) над веќе дефинираниот ==.
    friend bool operator!=(const Triangle &lhs, const Triangle &rhs) {
        return !(lhs == rhs);
    }

    // operator< -> Оператор за помало (Лексикографска споредба на страните една по една).
    friend bool operator<(const Triangle &lhs, const Triangle &rhs) {
        if (lhs.a < rhs.a) return true;
        if (rhs.a < lhs.a) return false;
        if (lhs.b < rhs.b) return true;
        if (rhs.b < lhs.b) return false;
        return lhs.c < rhs.c;
    }

    // operator<= -> „Помало или еднакво“ изведено преку негација на операторот за „поголемо“.
    friend bool operator<=(const Triangle &lhs, const Triangle &rhs) {
        return !(rhs < lhs);
    }

    // operator> -> „Поголемо од“ изведено со свртување на местата на lhs и rhs во операторот за помало.
    friend bool operator>(const Triangle &lhs, const Triangle &rhs) {
        return rhs < lhs;
    }

    // operator>= -> „Поголемо или еднакво“ изведено со негација на операторот за помало.
    friend bool operator>=(const Triangle &lhs, const Triangle &rhs) {
        return !(lhs < rhs);
    }

    // operator<< -> Овозможува печатење на објектот директно во cout (на пр. cout << t;).
    // ostream &os -> Референца до излезниот тек (Output Stream како cout). Се враќа како референца за да може да се надоврзува (cout << t << endl;).
    friend ostream &operator<<(ostream &os, const Triangle &obj) {
        return os << "a: " << obj.a << " b: " << obj.b << " c: " << obj.c;
    }

    // friend void swap -> Специјализирана функција за брза замена на местата на два триаголници во меморијата.
    // using std::swap -> Добра пракса која овозможува C++ автоматски да го избере најдобриот swap алгоритам за внатрешните типови.
    friend void swap(Triangle &lhs, Triangle &rhs) noexcept {
        using std::swap;
        swap(lhs.a, rhs.a);
        swap(lhs.b, rhs.b);
        swap(lhs.c, rhs.c);
    }

    // --- ФУНКЦИОНАЛНИ МЕТОДИ (Бизнис логика) ---

    // override -> Означува дека овој метод СТРОГО го препишува истоимениот метод од Shape.
    [[nodiscard]] int perimeter() const override {
        return a + b + c;
    }

    // double area() -> Пресметка на површина.
    // s -> Полупериметар.
    // Херонова формула спакувана во функцијата sqrt().
    [[nodiscard]] double area() const override {
        double s = perimeter() / 2.0;
        return sqrt(s * (s - a) * (s - b) * (s - c));
    }
};

