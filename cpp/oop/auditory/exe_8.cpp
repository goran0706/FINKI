// МОДИФИКАТОР: ВИРТУЕЛНО НАСЛЕДУВАЊЕ (Virtual Inheritance)
// ============================================================================
// СИНТАКСА: class Triangle : virtual public Shape  (или  public virtual Shape)
//
// ШТО ЗНАЧИ:
// - Му кажува на компајлерот дека сакаш да постои САМО ЕДНА споделена копија
//   од базната класа `Shape` во меморијата, дури и ако таа се наследува преку повеќе патеки.
// - Го решава познатиот „Дијамантски проблем“ (Diamond Problem) кај повеќекратното наследување.
//
// КОГА СЕ КОРИСТИ (USAGE):
// Се користи исклучиво при Повеќекратно Наследување (Multiple Inheritance), кога две
// различни класи наследуваат од ист родител, а потоа некоја четврта класа ги наследува двете деца.

// ============================================================================
// ПРИМЕР ЗА ДИЈАМАНТСКИОТ ПРОБЛЕМ (Зошто ни треба 'virtual'):
// ============================================================================
//
//       [ Shape ]  <-- Заеднички корен
//        /     \
//  [Scanner]  [Printer]  <-- Двете класи го наследуваат Shape
//        \     /
//     [Copier]  <-- Повеќекратно наследување (Ги наследува Scanner и Printer)
//
// ПРОБЛЕМОТ: Ако НЕ користиме `virtual`, класата `Copier` во себе ќе добие ДВЕ дупликат
// копии од `Shape` (една преку Scanner, една преку Printer). Ако `Shape` има променлива `id`,
// компајлерот ќе се збуни и ќе јави грешка: "error: request for member 'id' is ambiguous".
//
// РЕШЕНИЕТО: Со користење на `virtual public`, `Copier` добива само една единствена,
// паметно споделена копија од `Shape`.

class Scanner : virtual public Shape {
    // Кодот за Скенер...
};

class Printer : virtual public Shape {
    // Кодот за Принтер...
};

// Благодарение на 'virtual' погоре, сега Copier има само ОДНА копија од Shape!
class Copier : public Scanner, public Printer {
    // Паметен уред што и скенира и печати, без мемориски дупликати и конфликти
};

