    int input_a = 0, input_b = 0, input_c = 0;

    cout << "Внеси ги страните а, b и c: ";
    cin >> input_a >> input_b >> input_c;

    cout << "\n--- 1. КРЕИРАЊЕ НА ОБЈЕКТОТ ---" << endl;
    // Инстанцирање објект со параметарски конструктор
    Triangle t1(input_a, input_b, input_c);

    // Повикување на методите
    cout << "\n--- 2. ПОВИКУВАЊЕ НА МЕТОДИ И ПРЕСМЕТКИ ---" << endl;
    cout << "Информации за триаголникот t1: " << t1 << endl;
    cout << "Периметар: " << t1.perimeter() << endl;
    cout << "Плоштина: " << t1.area() << endl;

    cout << "\n--- 3. ДЕМОНСТРАЦИЈА НА COPY И MOVE ---" << endl;
    Triangle t2 = t1; // Се раѓа нов објект преку Copy Конструктор. t1 останува недопрен.

    t2 = t1; // t2 веќе постоеше, ова е Copy Assignment оператор.

    cout << "\n--- 4. УНИШТУВАЊЕ НА ОБЈЕКТИТЕ (Излез од main) ---" << endl;
