// Од тастатура се внесува непознат број на позитивни цели броеви.
// Внесувањето завршува кога ќе се внесе нешто што не е број.
// За секој број треба:
// - да се испечатат непарните цифри на бројот (почнувајќи од најмалкузначајната цифра)
// - да се отпечатат парните цифри на бројот (почнувајќи од најзначајната цифра).
// - да се испечати сума на непарни цифри
//
// Печатењето на цифрите и сумата на непарни цифри на даден број треба да се изврши во посебна рекурзивна функција.
// Доколку сумата и печатењето на цифрите го извршите со една рекурзивна функција, може да добиете 100% од поените.
// Користење на 2 или повеќе функции носи максимум 90%, а доколку се реши без рекурзивна функција, задачата носи максимум 60%.
//
// Input:                    Result:
// 123456789                 Digits: 9 7 5 3 1 2 4 6 8
// test                      Sum: 25
#include <iostream>
using namespace std;

int process_number(int n) {
    if (n == 0) {
        return 0;
    }

    int digit = n % 10;

    if (digit % 2 == 0) {
        int current_sum = process_number(n / 10);
        cout << digit << " ";
        return current_sum;
    } else {
        cout << digit << " ";
        return digit + process_number(n / 10);
    }
}

int main() {
    int n;

    while (cin >> n) {
        if (n == 0) {
            cout << "Digits: 0" << endl;
            cout << "Sum: 0" << endl;
            continue;
        }

        cout << "Digits: ";
        int total_sum = process_number(n);
        cout << endl;

        cout << "Sum: " << total_sum << endl;
    }

    return 0;
}
