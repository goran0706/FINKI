// со должина помеѓу 1 и 3 (вклучително).
// Сегментот мора да е разделен од не-буква (или крај на ред).
//
// Да се најде линијата со НАЈВЕЌЕ такви сегменти.
// Да се испечати:  <бројот>: <линијата>
//
// Пример:
//   Влез:
//     ab 1 cd ef
//     x yy zzz wwww
//   Излез: 3: ab 1 cd ef
//   (ab=2, cd=2, ef=2 → 3 сегменти; x=1,yy=2,zzz=3,wwww=4→ само 3)
