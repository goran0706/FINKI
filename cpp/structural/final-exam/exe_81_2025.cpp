// Се читаат N (редови) и M (колони), па N×M матрица цели броеви.
// За секој ред i (0 до N-1), да се избројат елементите за кои важи:
// елементот е ПАРЕН И позицијата (i+j) е ПАРНА, ИЛИ  елементот е НЕПАРЕН И позицијата (i+j) е НЕПАРНА.
// Да се испечати: "<i>: <броj>" за секој ред.
//
// Пример (N=2, M=3):
//   Матрица:
//     2 3 4
//     1 2 3
//   Ред 0: (2,парен,0+0=парна)✓ (3,непарен,0+1=непарна)✓ (4,парен,0+2=парна)✓ → 3
//   Ред 1: (1,непарен,1+0=непарна)✓ (2,парен,1+1=непарна)✗ (3,непарен,1+2=парна)✗ → 1
//   Излез:
//     0: 3
//     1: 1

#include <iostream>
using namespace std;

int main() {
	int n, m;
	cin >> n >> m;

	int a[100][100];

	for (int i = 0; i < n; i++) {
		for (int j = 0; j < m; j++) {
			cin >> a[i][j];
		}
	}

	for (int i = 0; i < n; i++) {
		int count = 0;

		for (int j = 0; j < m; j++) {
			if (a[i][j] % 2 == 0 && (i + j) % 2 == 0 || a[i][j] % 2 != 0 && (i + j) % 2 != 0) {
				count++;
			}
		}

		cout << i << ":" << count << endl;
	}

	return 0;
}
