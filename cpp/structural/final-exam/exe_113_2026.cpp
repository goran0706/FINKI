// Од тастатура се внесува димензии на матрица (n, m < 50), по што се внесуваат елементите од матрицата.
// Потоа се внесуваат индексите на еден елемент од матрицата.
// Потребно е да се најде сумата на елементите кои го прават најголемиот впишан ромб со центар во дадениот елемент.
// Најголем впишан ромб претставува ромбот ограничен од најдолгата низа од елементи од матрицата
// кои лежат или се паралелни со главната и споредната дијагонала во матрицата.
#include <iostream>
#include <cmath>     // Потребно за abs()
#include <algorithm> // Потребно за min()
using namespace std;

int main() {
    int n, m;
    cin >> n >> m;

    int A[50][50];
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < m; j++) {
            cin >> A[i][j];
        }
    }

    int x, y;
    cin >> x >> y;

    // 1. Го наоѓаме максималниот можен радиус 'r' за ромбот да биде целосно впишан
    int max_r_up = x;
    int max_r_down = (n - 1) - x;
    int max_r_left = y;
    int max_r_right = (n - 1) - y;

    // Најмалото од овие растојанија ни го дава максималниот валиден радиус 'r'
    int r = min({max_r_up, max_r_down, max_r_left, max_r_right});

    int sum = 0;

    // Ако радиусот r е 0, ромбот е само самата централна точка
    if (r == 0) {
        sum = A[x][y];
    } else {
        // 2. Ги вртиме сите елементи и ги собираме само оние на растојание точно 'r'
        for (int i = 0; i < n; i++) {
            for (int j = 0; j < m; j++) {
                // Условот за ромб со радиус 'r': (i - x) + (j - y) == r
                if (abs(i - x) + abs(j - y) == r) {
                    sum += A[i][j];
                }
            }
        }
    }

    cout << sum << endl;

    return 0;
}
