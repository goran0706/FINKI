// Идентична логика со Задача 17, но со поинакво пресметување на N: наместо N² ≥ K, N се наоѓа со бројач i додека i² < K.
// (Резултатот е ист за K > 1.)
// Се чита K, се пополнува матрицата со ист snake-column образец и се печати.
//
// Влез:  K
// Излез: N×N матрица (snake по колони)
#include <iostream>
using namespace std;

int main() {
	int n, k;
	cin >> n >> k;

	int a[100][100];
	int count = 1;

	for (int j = 0; j < n; j++) {
		for (int i = 0; i < n; i++) {
			a[j % 2 == 0 ? i : n - 1 - i][j] = count++;
			if (count > k) count = 0;
		}
	}

	for (int i = 0; i < n; i++) {
		for (int j = 0; j < n; j++) {
			cout << a[i][j] << " ";
		}
		cout << endl;
	}
}
