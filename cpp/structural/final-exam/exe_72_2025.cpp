// Влез:  цели броеви до EOF
// Излез: до 5 вредности одделени со празно место

#include <iostream>
using namespace std;

int reverse_number(int n) {
	int reversed = 0;

	while (n > 0) {
		reversed = reversed * 10 + n % 10;
		n /= 10;
	}

	return reversed;
}

int process_number(int n) {
	int transformed = 0;

	while (n > 0) {
		int digit = n % 10;

		if (digit == 9) {
			digit = 7;
		}

		transformed = transformed * 10 + digit;
		n /= 10;
	}

	return reverse_number(transformed);
}

void bubble_sort(int a[], int n) {
	for (int i = 0; i < n - 1; i++) {
		for (int j = 0; j < n - 1 - i; j++) {
			if (a[j] > a[j + 1]) {
				int tmp = a[j];
				a[j] = a[j + 1];
				a[j + 1] = tmp;
			}
		}
	}
}

int main() {
	int a[1000];
	int n = 0;

	int x;
	while (cin >> x) {
		a[n++] = process_number(x);
	}

	bubble_sort(a, n);

	int limit = (n < 5) ? n : 5;

	for (int i = 0; i < limit; i++) {
		cout << a[i] << " ";
	}

	return 0;
}
