// Се чита цел број N, па N×N матрица.
// Да се конструира нова N×N матрица на следниов начин:
//   - Ако елементот е на главната дијагонала (i==j) И анти-дијагоналата (i+j==N-1): вредност = X + Y
//   - Ако е само на главната дијагонала (i==j): вредност = X
//   - Ако е само на анти-дијагоналата (i+j==N-1): вредност = Y
//   - Инаку: вредност = 0
// каде:
//  X = сума на сите елементи ПОД главната дијагонала (i>j)
//  Y = сума на сите елементи ПОД анти-дијагоналата (i+j > N-1)
//
// Влез:  N, па N×N матрица (float)
// Излез: новата N×N матрица

#include <iostream>
using namespace std;

int main() {
	int n;
	cin >> n;

	float a[100][100];

	for (int i = 0; i < n; i++) {
		for (int j = 0; j < n; j++) {
			cin >> a[i][j];
		}
	}

	float X = 0, Y = 0;

	// 1. пресметка на X и Y
	for (int i = 0; i < n; i++) {
		for (int j = 0; j < n; j++) {
			if (i > j) {
				X += a[i][j];
			}

			if (i + j > n - 1) {
				Y += a[i][j];
			}
		}
	}

	// 2. нова матрица
	float b[100][100];

	for (int i = 0; i < n; i++) {
		for (int j = 0; j < n; j++) {
			if (i == j && i + j == n - 1) {
				b[i][j] = X + Y;
			} else if (i == j) {
				b[i][j] = X;
			} else if (i + j == n - 1) {
				b[i][j] = Y;
			} else {
				b[i][j] = 0;
			}
		}
	}

	// 3. печатење
	for (int i = 0; i < n; i++) {
		for (int j = 0; j < n; j++) {
			cout << b[i][j] << " ";
		}
		cout << endl;
	}

	return 0;
}
