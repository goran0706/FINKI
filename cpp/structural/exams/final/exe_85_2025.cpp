// Се чита N, па низа од N цели броеви, па индекс K.
// Да се пресмета и испечати сумата на сите елементи од позиција K до крајот на низата (вклучително).
// Ако K > N, сумата е 0.
//
// Влез:  N, па N цели броеви, па K
// Излез: сумата
//
// Пример:
//   Влез: 5
//         10 20 30 40 50
//         2
//   Излез: 120   (30+40+50)
#include <iostream>
using namespace std;

int main() {
	int n;
	cin >> n;

	int a[100];
	for (int i = 0; i < n; i++) {
		cin >> a[i];
	}

	int k;
	cin >> k;

	if (k > n) {
		cout << 0 << endl;
		return 0;
	}

	int sum = 0;
	for (int i = k; i < n; i++) {
		sum += a[i];
	}

	cout << sum << endl;

	return 0;
}
