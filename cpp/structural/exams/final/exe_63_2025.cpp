// Се чита цел број N.
// Рекурзивно да се испечати опаѓачки шаблон:
//   Ред 1 : 1 2 3 ... N ... 3 2 1
//   Ред 2 : 1 2 3 ... (N-1) ... 2 1
//   ...
//   Ред N : 1
// (Секој ред е симетричен: расте до вредноста на редот, потоа опаѓа.)
//
// Пример (N=3):
//   123321
//   1221
//   1
#include <iostream>
using namespace std;

void process_number(int n, int i = 1) {
	if (n == 0) return;

	if (i <= n) {
		cout << i;
		process_number(n, i + 1);

		// Ако n е 1, не го печатиме десниот (опаѓачки) дел
		if (n > 1) {
			cout << i;
		}
	}

	if (i == 1) {
		cout << endl;
		process_number(n - 1, 1);
	}
}


int main() {
	int n;
	cin >> n;

	process_number(n);

	return 0;
}
