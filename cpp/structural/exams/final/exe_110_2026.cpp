// Од стандарден влез се чита матрица од реални броеви (3 < n,m < 50).
// Прво се читаат бројот на редици и колони на матрицата и во секој преостанат ред се внесува еден ред од матрицата (види пример).
// По читањето на матрицата, се внесуваат и 2 пара координати на матрицата (ред и колона) кои го репрезентираат горниот-лев и долниот-десен елемент од регионот.
// Потребно е да генеирате нова матрица во која ќе ги заматите сите елементи кои припаѓаат на регионот.
// Новодобиената матрица, во истиот формат, треба да се испечати (види пример).
//
// Пример:
// 3 4
// 1.00 2.00 3.00 4.00
// 5.00 6.00 7.00 8.00
// 9.00 0.00 1.00 2.00
// 0 1
// 2 2
//
// Резултат:
// 3 4
// 1.00 4.00 5.00 4.00
// 5.00 3.78 3.67 8.00
// 9.00 4.67 4.00 2.00
#include <iomanip>
#include <iostream>
using namespace std;

int main() {
    int n, m;
    cin >> n >> m;

    double A[100][100];
    double B[50][50];

    for (int i = 0; i < n; i++) {
        for (int j = 0; j < m; j++) {
            cin >> A[i][j];
        }
    }

    int x1, y1, x2, y2;
    cin >> x1 >> y1 >> x2 >> y2;

    for (int i = 0; i < n; i++) {
        for (int j = 0; j < m; j++) {
            // SIMPLE for TESTING
            // if (i >= x1 && i <= x2 && j >= y1 && j <= y2) {
            //     B[i][j] = 9.99;
            // }

            // ПРОСЛЕДУВАЊЕ: Дали моменталниот елемент е внатре во бараниот правоаголник?
            if (i >= x1 && i <= x2 && j >= y1 && j <= y2) {
                double sum = 0;
                int count = 0;

                // Ги проверуваме сите соседи околу (i, j)
                for (int ni = i - 1; ni <= i + 1; ni++) {
                    for (int nj = j - 1; nj <= j + 1; nj++) {
                        // Проверка дали соседот е во рамките на матрицата
                        if (ni >= 0 && ni < n && nj >= 0 && nj < m) {
                            sum += A[ni][nj]; // Читаме ОД ОРИГИНАЛНАТА матрица
                            count++;
                        }
                    }
                }

                // Го запишуваме заматениот просек во помошната матрица B
                B[i][j] = sum / count;
            } else {
                // Ако елементот е НАДВОР од регионот, само го препишуваме непроменет
                B[i][j] = A[i][j];
            }
        }
    }

    cout << n << " " << m << endl;
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < m; j++) {
            cout << fixed << setprecision(2) << B[i][j] << " ";
        }
        cout << endl;
    }

    return 0;
}
