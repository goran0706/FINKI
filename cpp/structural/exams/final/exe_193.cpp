// Четиринасочник претставува матрица во која се испишани зборови хоризонотално и вертикално, одлево-надесно и оддесно-налево.
// Притоа секој елемент од матрицата претставува буква од англиската азбука.
//
// пример скриени зборови: HAIR, OLE (прецртани), FISH, TOE (подвлечени)
// T H A I R E
// E S N K N E
// M I M J O L
// M F S P S T
// I F G E L O
// X U T Y O E
//
// Од стандарден влез се чита квадратна матрица од ред n (3 <= n <= 50), составена од знаци.
// Прво се чита бројот n - бројот на редици (колони) на матрицата, а потоа и самите елементи на матрицата (види пример).
// По читањето на матрицата, од стандарден влез се внесува збор составен од максимум 10 букви.
// Ваша задача е да определите дали тој збор се наоѓа во четиринасочникот (хоризонтално или вертикално, одлево-надесно или оддесно-налево).
// Потребно е да се испечати локацијата (ред, колона) на првата и последната буква од зборот.
// Доколку зборот повеќепати се наоѓа во четеринасочникот, треба да се испечати првото појавување, гледано елемент по елемент како што се чита матрицата.
// Доколку не се пронајде зборот, тогаш се печати Not Found.

// For example:
// Input
//
// 4
// T H K I E E N K M A E J M I E P
// KNEE
//
// Result
// 0, 2 -> 3, 2

// Input
// 6
// T H N I R E E E A K N E M A M A M A M T A P S T L R M M L O R U A Y O E
// MAMA
//
// Result
// 2, 0 -> 2, 3
#include <iostream>
#include <cstring>

using namespace std;

int main() {
    int n;
    if (!(cin >> n)) return 0;

    char a[50][50];
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++) {
            cin >> a[i][j];
        }
    }

    char word[11];
    cin >> word;
    int len = strlen(word);

    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++) {
            // 1. Проверка ОД ЛЕВО НА ДЕСНО
            if (j + len <= n) {
                // Проверка дали зборот воопшто собира до крајот на редот
                bool match = true;
                for (int k = 0; k < len; k++) {
                    if (a[i][j + k] != word[k]) {
                        match = false;
                        break;
                    }
                }
                if (match) {
                    cout << i << ", " << j << " -> " << i << ", " << j + len - 1 << endl;
                    return 0; // Најдено е првото појавување, прекинуваме веднаш
                }
            }

            // 2. Проверка ОД ДЕСНО НА ЛЕВО
            if (j - len + 1 >= 0) {
                // Дали има доволно букви на лево
                bool match = true;
                for (int k = 0; k < len; k++) {
                    if (a[i][j - k] != word[k]) {
                        match = false;
                        break;
                    }
                }
                if (match) {
                    cout << i << ", " << j << " -> " << i << ", " << j - len + 1 << endl;
                    return 0;
                }
            }

            // 3. Проверка ОД ГОРЕ НА ДОЛУ
            if (i + len <= n) {
                // Дали има доволно простор на долу
                bool match = true;
                for (int k = 0; k < len; k++) {
                    if (a[i + k][j] != word[k]) {
                        match = false;
                        break;
                    }
                }
                if (match) {
                    cout << i << ", " << j << " -> " << i + len - 1 << ", " << j << endl;
                    return 0;
                }
            }

            // 4. Проверка ОД ДОЛУ НА ГОРЕ
            if (i - len + 1 >= 0) {
                // Дали има доволно простор на горе
                bool match = true;
                for (int k = 0; k < len; k++) {
                    if (a[i - k][j] != word[k]) {
                        match = false;
                        break;
                    }
                }
                if (match) {
                    cout << i << ", " << j << " -> " << i - len + 1 << ", " << j << endl;
                    return 0;
                }
            }
        }
    }

    // Ако ги поминавме сите позиции и ништо не врати 'return 0', зборот го нема
    cout << "Not Found" << endl;
    return 0;
}
