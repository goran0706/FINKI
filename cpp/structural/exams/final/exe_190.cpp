// Еден елемент се заматува ако се најде аритметичка средина на елементот и сите негови соседи.
// Сосед на еден елемент се сите елементи кои припаѓаат на матрицата и се околу истиот елемент (хоризонтално, вертикално и дијагонално).
// Од стандарден влез се чита матрица од реални броеви (3 < n,m < 50).
// Прво се читаат бројот на редици и колони на матрицата и во секој преостанат ред се внесува еден ред од матрицата (види пример).
// По читањето на матрицата, се внесуваат и 2 пара координати на матрицата (ред и колона) кои го репрезентираат горниот-лев и долниот-десен елемент од регионот.
// Потребно е да генеирате нова матрица во која ќе ги заматите сите елементи кои припаѓаат на регионот.
//
// Новодобиената матрица, во истиот формат, треба да се испечати (види пример).
// Пример:
//
// 3 4
// 1.00 2.00 3.00 4.00
// 5.00 6.00 7.00 8.00
// 9.00 0.00 1.00 2.00
//
// 0 1
// 2 2
//
// Резултат:
// 3 4
// 1.00 4.00 5.00 4.00
// 5.00 3.78 3.67 8.00
// 9.00 4.67 4.00 2.00
//
// For example:
// Input
// 3 3
// 1 2 3
// 4 5 6
// 7 8 9
// 0 0
// 2 2
//
// Result
// 3 3.5 4
// 4.5 5 5.5
// 6 6.5 7
#include <iostream>
#include <iomanip>

using namespace std;

int main() {
	int n, m;
	if (!(cin >> n >> m)) return 0;

	double a[50][50];
	double result[50][50];

	// 1) Читање на почетната матрица и копирање во резултатната
	for (int i = 0; i < n; i++) {
		for (int j = 0; j < m; j++) {
			cin >> a[i][j];
			result[i][j] = a[i][j]; // Иницијално резултатот е ист како оригиналот
		}
	}

	// 2) Читање на координатите за регионот
	int r1, c1, r2, c2;
	cin >> r1 >> c1; // Горен-лев агол
	cin >> r2 >> c2; // Долен-десен агол

	// 3) Изминување и заматување САМО на елементите во регионот
	for (int i = r1; i <= r2; i++) {
		for (int j = c1; j <= c2; j++) {
			double sum = 0;
			int count = 0;

			// Ги проверуваме сите 9 позиции (самиот елемент + 8 соседи околу него)
			// Одиме од i-1 до i+1, и од j-1 до j+1
			for (int r = i - 1; r <= i + 1; r++) {
				for (int c = j - 1; c <= j + 1; c++) {
					// Проверка дали позицијата (r, c) е внатре во границите на матрицата
					if (r >= 0 && r < n && c >= 0 && c < m) {
						sum += a[r][c];
						count++;
					}
				}
			}

			// Новата вредност е аритметичка средина од самиот елемент и валидните соседи
			result[i][j] = sum / count;
		}
	}

	// 4) Печатење на резултатот во бараниот формат
	cout << n << " " << m << endl;
	for (int i = 0; i < n; i++) {
		for (int j = 0; j < m; j++) {
			// Задачата во првиот пример бара приказ со 2 децимали
			cout << fixed << setprecision(2) << result[i][j] << " ";
		}
		cout << endl;
	}

	return 0;
}
