// Се чита цел број K.
// Да се пополни квадратна матрица со страна N (каде N е најмалиот цел број таков што N² ≥ K) со броеви 1..K по колони, наизменично:
//   - Парни колони (0,2,4,...): пополнуваат ОДОЗГОРА надолу
//   - Непарни колони (1,3,5,...): пополнуваат ОДОЗДОЛА нагоре
//
// Преостанатите позиции (по K) се пополнуваат со 0.
// Да се испечати матрицата.
//
// Влез:  K
// Излез: N×N матрица
//
// Пример (K=6, N=3):
// 1 6 7
// 2 5 0
// 3 4 0

#include <iostream>
using namespace std;

int main() {
	int k, n;
	cin >> k >> n;

	int a[100][100];

	int count = 0;

	for (int j = 0; j < n; j++) {
		for (int i = 0; i < n; i++) {
			const int index = j % 2 == 0 ? i : n - 1 - i;
			a[index][j] = count <= k ? ++count : 0;
		}
	}

	for (int i = 0; i < n; i++) {
		for (int j = 0; j < n; j++) {
			cout << a[i][j] << " ";
		}
		cout << endl;
	}

	return 0;
}
