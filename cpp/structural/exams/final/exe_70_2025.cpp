// Се читаат N (редови), M (колони), па N×M матрица цели броеви.
// Потоа се читаат координати X, Y, Z, K.
// Да се постават на 0 сите елементи во правоаголниот регион дефиниран
// со горниот-лев агол (X,Y) и долниот-десен агол (Z,K) (вклучувајќи ги граничните елементи).
// Да се испечати модифицираната матрица.
//
// Влез:  N M, па N×M матрица, па X Y Z K
// Излез: модифицирана N×M матрица

#include <iostream>
using namespace std;

int main() {
	int n, m;
	cin >> n >> m;

	int a[100][100];

	for (int i = 0; i < n; i++) {
		for (int j = 0; j < m; j++) {
			cin >> a[i][j];
		}
	}

	int x, y, z, k;
	cin >> x >> y >> z >> k;

	// SOLUTION 1:
	for (int i = x; i <= z; i++) {
		for (int j = y; j <= k; j++) {
			a[i][j] = 0;
		}
	}

	// SOLUTION 2:
	for (int i = 0; i < n; i++) {
		for (int j = 0; j < m; j++) {
			if (i >= x && i <= z && j >= y && j <= k) {
				a[i][j] = 0;
			}
		}
	}

	for (int i = 0; i < n; i++) {
		for (int j = 0; j < m; j++) {
			cout << a[i][j] << " ";
		}
		cout << endl;
	}

	return 0;
}
