#include <iostream>
using namespace std;

/*
=== ВИЗУЕЛИЗАЦИЈА НА ИЗВРШУВАЊЕТО (За N = 5) ===

Повик во меморијата:                        Што се печати во моментот:
-----------------------------------------------------------------------------------
process_number(5, 1)            ──>         1
  process_number(5, 2)          ──>         2
    process_number(5, 3)        ──>         3
      process_number(5, 4)      ──>         4
        process_number(5, 5)    ──>         5  (i < n паѓа, се враќа назад)
      [се враќа во (5,4)]       ──>         4
    [се враќа во (5,3)]         ──>         3
  [се враќа во (5,2)]           ──>         2
[се враќа во (5,1)]             ──>         1  (испечатено: 123454321)
[удира во if (i == 1)]          ──>         \n (нов ред)
-----------------------------------------------------------------------------------
process_number(4, 1)            ──>         1
  process_number(4, 2)          ──>         2
    process_number(4, 3)        ──>         3
      process_number(4, 4)      ──>         4  (i < n паѓа, се враќа назад)
    [се враќа во (4,3)]         ──>         3
  [се враќа во (4,2)]           ──>         2
[се враќа во (4,1)]             ──>         1  (испечатено: 1234321)
[удира во if (i == 1)]          ──>         \n (нов ред)
-----------------------------------------------------------------------------------
process_number(3, 1)            ──>         1
  process_number(3, 2)          ──>         2
    process_number(3, 3)        ──>         3  (i < n паѓа, се враќа назад)
  [се враќа во (3,2)]           ──>         2
[се враќа во (3,1)]             ──>         1  (испечатено: 12321)
[удира во if (i == 1)]          ──>         \n (нов ред)
-----------------------------------------------------------------------------------
process_number(2, 1)            ──>         1
  process_number(2, 2)          ──>         2  (i < n паѓа, се враќа назад)
[се враќа во (2,1)]             ──>         1  (испечатено: 121)
[удира во if (i == 1)]          ──>         \n (нов ред)
-----------------------------------------------------------------------------------
process_number(1, 1)            ──>         1  (1 < 1 паѓа веднаш, се враќа назад)
[удира во if (i == 1)]          ──>         \n (нов ред)
-----------------------------------------------------------------------------------
process_number(0, 1)            ──>         (n == 0 -> КРАЈ НА СЀ)
-----------------------------------------------------------------------------------
*/
void process_number(int n, int i = 1) {
    if (n == 0) return;

    cout << i;

    if (i < n) {
        process_number(n, i + 1);
        cout << i;
    }

    if (i == 1) {
        cout << endl;
        process_number(n - 1, 1);
    }
}

int main() {
    if (int n; cin >> n) {
        process_number(n);
    }

    return 0;
}
