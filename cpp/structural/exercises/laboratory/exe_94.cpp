// Да се напише програма која вчитува квадратна матрица.
// На почетокот се внесува бројот на редици и колони N на матрицата, а потоа и елементите на матрицата.
// Да се трансформира матрицата на тој начин што секој негативен број во неа би се заменил со збирот на неговите соседи.
// Соседи на даден број во матрица се броевите до него (гледано хоризонтално и вертикално).
// --
// Write a program that reads a square matrix.
// Initially, the number of rows and columns N of the matrix is read, followed by the elements of the matrix.
// Transform the matrix so that every negative number is replaced with the sum of its neighbors.
// The neighbors of a given number in a matrix are the numbers adjacent to it (horizontally and vertically).
//
// For example:
// Input
// 3
// 4
// -6
// 8
// 10
// -5
// 1
// 3
// -6
// 15
//
// Result
// 4 7 8
// 10 12 1
// 3 30 15
