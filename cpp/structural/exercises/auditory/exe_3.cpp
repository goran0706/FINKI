// Да се напише програма која ќе ги отпечати на екран остатоците при делењето на бројот 19 со 2, 3, 5 и 8.

#include <iostream>
using namespace std;

int main() {
    cout << "Reminders:" << endl;
    cout << "19 % 2 = " << 19 % 2 << endl;
    cout << "19 % 3 = " << 19 % 3 << endl;
    cout << "19 % 5 = " << 19 % 5 << endl;
    cout << "19 % 8 = " << 19 % 8 << endl;

    return 0;
}
