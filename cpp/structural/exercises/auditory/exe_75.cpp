// Од стандарден влез се читаат едноцифрени броеви, се додека не се прочита нешто што не е број.
// Да се испечати на екран статистика колку пати се јавува секоја цифра меѓу прочитаните броеви.

#include <iostream>
using namespace std;

int main() {
    int n;
    int a[10] = {};

    while (cin >> n) {
        if (n >= 0 && n < 10) {
            a[n]++;
        }

        for (int i = 0; i < 10; i++) {
            cout << i << " : " << a[i] << endl;
        }
    }

    return 0;
}
